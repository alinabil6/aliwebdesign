import { Router } from "express";
import fs from "fs";
import { v4 as uuidv4 } from "uuid";
import { resolveLibraryPath, storeInLibrary } from "../lib/files.js";
import { getDesignById, insertDesign } from "../lib/db.js";
import { hasReadyAccount } from "../lib/accounts.js";
import { runBatch } from "../lib/queue.js";
import { buildPrompt } from "../prompts/edit.js";

const router = Router();

// POST /api/edit/:designId
// body: { edit_instruction }. Edits an *already-generated* result.
// Always inserts a NEW row (parent_id = the edited design) and a NEW file —
// never overwrites the original row or file (spec §6 Edit + §11 #8).
router.post("/:designId", async (req, res) => {
  try {
    const parent = getDesignById(req.params.designId);
    if (!parent) return res.status(404).json({ error: "Design not found" });

    const instruction = String(req.body?.edit_instruction || "").trim();
    if (!instruction) {
      return res.status(400).json({ error: "edit_instruction is required" });
    }

    if (!hasReadyAccount()) {
      return res.status(503).json({ error: "No Gemini account is ready — open the Accounts tab and sign in" });
    }

    // The input is the parent's generated output file (sanitized to stay
    // inside /library).
    const inputAbs = resolveLibraryPath(parent.output_image_path);
    if (!inputAbs || !fs.existsSync(inputAbs)) {
      return res.status(404).json({ error: "Source image file is missing" });
    }

    const prompt = buildPrompt({ edit_instruction: instruction });
    const [result] = await runBatch([{ prompt, imagePaths: [inputAbs] }]);

    // runBatch swallows per-task failures and returns [] — a missing result
    // means Gemini refused (safety) or timed out, never a silent success.
    if (!result || !result.buffer) {
      console.warn(
        `[Edit] Slot returned no image buffer. Gemini may have generated a text-only refusal or the generation timed out.`
      );
      throw new Error("No image generated by Gemini for this design (possible safety refusal or timeout).");
    }

    const out = storeInLibrary(result.buffer, `${uuidv4()}.png`);
    const row = insertDesign({
      id: uuidv4(),
      feature: "edit",
      parent_id: parent.id,
      source_image_path: parent.output_image_path, // what this version was edited from
      output_image_path: out.rel,
      prompt_used: prompt,
      user_input: instruction,
    });

    res.json({ design: row });
  } catch (err) {
    console.error("edit failed:", err);
    res.status(500).json({ error: "Edit failed" });
  }
});

export default router;