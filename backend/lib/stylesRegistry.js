/** Search styles by keyword tokens. */
export function findStylesByKeyword(keyword) {
    const k = String(keyword || "").trim().toLowerCase();
    if (!k) return [];
    return STYLES.filter(
        (s) =>
            s.keywords?.some((kw) => kw.toLowerCase().includes(k)) ||
            s.name.toLowerCase().includes(k) ||
            s.directive.toLowerCase().includes(k)
    );
}

/** Get taxonomy summary mapping categories to style counts. */
export function getTaxonomies() {
    const counts = {};
    for (const s of STYLES) {
        counts[s.category] = (counts[s.category] || 0) + 1;
    }
    return Object.entries(STYLE_CATEGORIES).map(([id, label]) => ({
        id,
        label,
        count: counts[id] || 0,
    }));
}
