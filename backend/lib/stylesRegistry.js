const byId = new Map(STYLES.map((s) => [s.id, s]));

// Pure structural layouts (category "layout_structural") are NOT artistic
// styles — they are composition templates (text top/bottom, grid layers,
// stripes, polka-dot backdrops, etc.). They are excluded from every LLM
// prompt so the model only ever picks genuine visual/artistic aesthetics.
const ARTISTIC_CATEGORIES = new Set([
    "scientific_botanical",
    "mascot_humor",
    "retro_typography",
    "aesthetic_lifestyle",
    "seasonal_fall_holiday",
]);

/** The catalog restricted to genuine artistic styles (no layout tags). */
export function artisticStyles() {
    return STYLES.filter((s) => ARTISTIC_CATEGORIES.has(s.category));
}

export function getStyleById(id) {
    return byId.get(id) || null;
}

export function getStyleOrDefault(id) {
    return byId.get(id) || byId.get(DEFAULT_STYLE_ID);
}

/**
 * Fuzzy-match a user-typed style phrase against the catalog. Returns the full
 * style record when the phrase contains / closely matches a known style name
 * (case-insensitive, loose token overlap); returns null when it's a genuinely
 * custom phrase that should be injected verbatim instead.
 */
export function findStyleByName(phrase) {
    const q = String(phrase || "").trim().toLowerCase();
    if (!q) return null;
    // 1) exact name match (case-insensitive)
    const exact = STYLES.find((s) => s.name.toLowerCase() === q);
    if (exact) return exact;
    // 2) substring match — the phrase contains the style name, or vice versa
    const contains = STYLES.find(
        (s) => s.name.toLowerCase().includes(q) || q.includes(s.name.toLowerCase())
    );
    if (contains) return contains;
    // 3) token overlap — 60%+ of the phrase's words appear in the style name
    const tokens = q.split(/[^a-z0-9]+/).filter(Boolean);
    if (tokens.length >= 2) {
        let best = null;
        let bestOverlap = 0;
        for (const s of STYLES) {
            const nameTokens = s.name.toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
            const overlap = tokens.filter((t) => nameTokens.includes(t)).length;
            if (overlap > bestOverlap) {
                bestOverlap = overlap;
                best = s;
            }
        }
        if (best && bestOverlap / tokens.length >= 0.6) return best;
    }
    return null;
}

/** Compact one-line-per-style list for LLM prompts (artistic styles only). */
export function styleSummaries() {
    return artisticStyles()
        .map((s) => `${s.id} (${s.name}, ${s.category}): ${s.directive}`)
        .join("\n");
}

/** Bare ID list for constrained JSON output (artistic styles only). */
export function styleIdList() {
    return artisticStyles()
        .map((s) => s.id)
        .join(", ");
}

